def add_after(anchor, text, style):
    p = anchor._parent.add_paragraph(style=style)
    p.add_run(text)
    # Move the newly-created paragraph directly after the anchor.
    anchor._p.addnext(p._p)
    return p


def main():
    d = Document(DOC)
    done = 0
    for target, entries in BLOCKS.items():
        matches = [p for p in d.paragraphs if p.text.strip() == target]
        if len(matches) != 1:
            raise RuntimeError(f"target not unique: {target!r} ({len(matches)})")
        anchor = matches[0]
        for kind, text in entries:
            style = "Heading 2" if kind == "heading" else "Normal"
            anchor = add_after(anchor, text, style)
            if kind == "para":
                anchor.paragraph_format.first_line_indent = Cm(0.74)
                anchor.paragraph_format.line_spacing = 1.42
                anchor.paragraph_format.space_after = Pt(0)
            else:
                anchor.paragraph_format.keep_with_next = True
            done += 1
    d.save(DOC)
    print(f"inserted {done} editable paragraphs/headings into {DOC}")


if __name__ == "__main__":
    main()
